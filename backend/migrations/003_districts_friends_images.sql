ALTER TABLE DISTRICTS ADD CONSTRAINT CK_DISTRICTS_BUSAN_NAME CHECK (
    NAME IN (
        '강서구', '금정구', '기장군', '남구',
        '동구', '동래구', '부산진구', '북구',
        '사상구', '사하구', '서구', '수영구',
        '연제구', '영도구', '중구', '해운대구'
    )
);

MERGE INTO DISTRICTS target
USING (
    SELECT '강서구' NAME FROM DUAL UNION ALL
    SELECT '금정구' FROM DUAL UNION ALL
    SELECT '기장군' FROM DUAL UNION ALL
    SELECT '남구' FROM DUAL UNION ALL
    SELECT '동구' FROM DUAL UNION ALL
    SELECT '동래구' FROM DUAL UNION ALL
    SELECT '부산진구' FROM DUAL UNION ALL
    SELECT '북구' FROM DUAL UNION ALL
    SELECT '사상구' FROM DUAL UNION ALL
    SELECT '사하구' FROM DUAL UNION ALL
    SELECT '서구' FROM DUAL UNION ALL
    SELECT '수영구' FROM DUAL UNION ALL
    SELECT '연제구' FROM DUAL UNION ALL
    SELECT '영도구' FROM DUAL UNION ALL
    SELECT '중구' FROM DUAL UNION ALL
    SELECT '해운대구' FROM DUAL
) source
ON (target.NAME = source.NAME)
WHEN NOT MATCHED THEN INSERT (NAME) VALUES (source.NAME);

ALTER TABLE APP_USERS ADD CONSTRAINT FK_APP_USERS_DISTRICT
    FOREIGN KEY (DISTRICT_NAME) REFERENCES DISTRICTS(NAME);

CREATE TABLE FRIENDSHIPS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_CODE VARCHAR2(20) NOT NULL REFERENCES APP_USERS(USER_CODE),
    FRIEND_USER_CODE VARCHAR2(20) NOT NULL REFERENCES APP_USERS(USER_CODE),
    CONSTRAINT UQ_FRIENDSHIP UNIQUE (USER_CODE, FRIEND_USER_CODE),
    CONSTRAINT CK_FRIENDSHIP_NOT_SELF CHECK (USER_CODE <> FRIEND_USER_CODE)
);

CREATE INDEX IX_FRIENDSHIPS_USER_CODE ON FRIENDSHIPS(USER_CODE);
CREATE INDEX IX_FRIENDSHIPS_FRIEND_CODE ON FRIENDSHIPS(FRIEND_USER_CODE);

COMMIT;
