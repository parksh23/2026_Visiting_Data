CREATE TABLE SAVED_MISSIONS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_CODE VARCHAR2(20) NOT NULL,
    MISSION_ID NUMBER NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_SAVED_MISSIONS_USER
        FOREIGN KEY (USER_CODE) REFERENCES APP_USERS(USER_CODE),
    CONSTRAINT FK_SAVED_MISSIONS_MISSION
        FOREIGN KEY (MISSION_ID) REFERENCES MISSIONS(MISSION_ID),
    CONSTRAINT UQ_SAVED_MISSION UNIQUE (USER_CODE, MISSION_ID)
);

CREATE INDEX IX_SAVED_MISSIONS_USER_CODE ON SAVED_MISSIONS(USER_CODE);
CREATE INDEX IX_SAVED_MISSIONS_MISSION_ID ON SAVED_MISSIONS(MISSION_ID);

COMMIT;
