CREATE TABLE USER_AGREEMENTS (
    ID          NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_CODE   VARCHAR2(20)  NOT NULL,
    DOC_SLUG    VARCHAR2(30)  NOT NULL,
    DOC_VERSION VARCHAR2(20)  NOT NULL,
    AGREED      NUMBER(1)     DEFAULT 1 NOT NULL,
    AGREED_AT   TIMESTAMP     NOT NULL,
    CREATED_AT  TIMESTAMP     DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_USER_AGREEMENTS_USER
        FOREIGN KEY (USER_CODE) REFERENCES APP_USERS(USER_CODE),
    CONSTRAINT CK_USER_AGREEMENTS_DOC
        CHECK (DOC_SLUG IN ('terms','privacy','location')),
    CONSTRAINT CK_USER_AGREEMENTS_AGREED
        CHECK (AGREED IN (0,1))
);

CREATE INDEX IX_USER_AGREEMENTS_USER_CODE ON USER_AGREEMENTS(USER_CODE);
CREATE INDEX IX_USER_AGREEMENTS_DOC ON USER_AGREEMENTS(DOC_SLUG, DOC_VERSION);

COMMIT;
