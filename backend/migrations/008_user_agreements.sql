CREATE TABLE USER_AGREEMENTS (
    ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_CODE VARCHAR2(20) NOT NULL,
    DOCUMENT_SLUG VARCHAR2(20) NOT NULL,
    VERSION VARCHAR2(20) NOT NULL,
    AGREED_AT TIMESTAMP NOT NULL,
    CONSTRAINT FK_USER_AGREEMENTS_USER
        FOREIGN KEY (USER_CODE) REFERENCES APP_USERS(USER_CODE),
    CONSTRAINT CK_USER_AGREEMENTS_DOCUMENT
        CHECK (DOCUMENT_SLUG IN ('terms', 'privacy', 'location')),
    CONSTRAINT UQ_USER_AGREEMENT
        UNIQUE (USER_CODE, DOCUMENT_SLUG, VERSION)
);

CREATE INDEX IX_USER_AGREEMENTS_USER_CODE ON USER_AGREEMENTS(USER_CODE);

COMMIT;
