CREATE TABLE USER_SETTINGS (
    USER_CODE           VARCHAR2(20) PRIMARY KEY,
    MISSION_RESULT      NUMBER(1) DEFAULT 1 NOT NULL,
    NEW_MISSION         NUMBER(1) DEFAULT 1 NOT NULL,
    RANKING_CHANGE      NUMBER(1) DEFAULT 0 NOT NULL,
    NIGHT_MUTE          NUMBER(1) DEFAULT 1 NOT NULL,
    MARKETING           NUMBER(1) DEFAULT 0 NOT NULL,
    MARKETING_AGREED_AT TIMESTAMP NULL,
    CONSTRAINT FK_USER_SETTINGS_USER
        FOREIGN KEY (USER_CODE) REFERENCES APP_USERS(USER_CODE),
    CONSTRAINT CK_USER_SETTINGS_FLAGS CHECK (
        MISSION_RESULT IN (0,1) AND NEW_MISSION IN (0,1)
        AND RANKING_CHANGE IN (0,1) AND NIGHT_MUTE IN (0,1)
        AND MARKETING IN (0,1)
    )
);

CREATE TABLE PUSH_TOKENS (
    ID         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_CODE  VARCHAR2(20) NOT NULL,
    TOKEN      VARCHAR2(512) NOT NULL,
    PLATFORM   VARCHAR2(20) DEFAULT 'android' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PUSH_TOKENS_USER
        FOREIGN KEY (USER_CODE) REFERENCES APP_USERS(USER_CODE),
    CONSTRAINT UQ_PUSH_TOKENS_TOKEN UNIQUE (TOKEN),
    CONSTRAINT CK_PUSH_TOKENS_PLATFORM CHECK (PLATFORM IN ('android','ios'))
);

CREATE INDEX IX_PUSH_TOKENS_USER_CODE ON PUSH_TOKENS(USER_CODE);

CREATE TABLE PENDING_PUSHES (
    ID           NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    USER_CODE    VARCHAR2(20) NOT NULL,
    TITLE        VARCHAR2(200) NOT NULL,
    BODY         VARCHAR2(1000) NOT NULL,
    DATA_JSON    CLOB NULL,
    SCHEDULED_AT TIMESTAMP NOT NULL,
    SENT_AT      TIMESTAMP NULL,
    STATUS       VARCHAR2(20) DEFAULT 'pending' NOT NULL,
    CREATED_AT   TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PENDING_PUSHES_USER
        FOREIGN KEY (USER_CODE) REFERENCES APP_USERS(USER_CODE),
    CONSTRAINT CK_PENDING_PUSHES_STATUS
        CHECK (STATUS IN ('pending','sent','failed'))
);

CREATE INDEX IX_PENDING_PUSHES_DUE
    ON PENDING_PUSHES(STATUS, SCHEDULED_AT);
CREATE INDEX IX_PENDING_PUSHES_USER_CODE
    ON PENDING_PUSHES(USER_CODE);

