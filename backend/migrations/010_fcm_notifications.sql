CREATE TABLE PUSH_DELIVERY_LOGS (
    ID                NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    IDEMPOTENCY_KEY   VARCHAR2(200) NOT NULL UNIQUE,
    USER_CODE         VARCHAR2(20) NOT NULL,
    NOTIFICATION_TYPE VARCHAR2(30) NOT NULL,
    SUCCESS_COUNT     NUMBER DEFAULT 0 NOT NULL,
    FAILURE_COUNT     NUMBER DEFAULT 0 NOT NULL,
    STATUS            VARCHAR2(20) NOT NULL,
    ERROR_MESSAGE     VARCHAR2(1000),
    CREATED_AT        TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
    CONSTRAINT FK_PUSH_LOG_USER
        FOREIGN KEY (USER_CODE) REFERENCES APP_USERS(USER_CODE),
    CONSTRAINT CK_PUSH_LOG_STATUS
        CHECK (STATUS IN ('processing','queued','sent','partial','failed','skipped'))
);

CREATE INDEX IX_PUSH_LOG_USER_CODE
    ON PUSH_DELIVERY_LOGS(USER_CODE);

CREATE TABLE NOTIFICATION_JOB_STATE (
    JOB_NAME    VARCHAR2(50) PRIMARY KEY,
    LAST_RUN_AT TIMESTAMP NOT NULL
);

